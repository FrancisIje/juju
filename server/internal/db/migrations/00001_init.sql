CREATE TABLE organizations (
    id         BIGSERIAL PRIMARY KEY,
    name       TEXT        NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE projects (
    id              BIGSERIAL PRIMARY KEY,
    organization_id BIGINT      NOT NULL REFERENCES organizations (id),
    name            TEXT        NOT NULL,
    -- Public key: shipped inside apps, so anyone can read it. It only allows
    -- *sending* events.
    public_key      TEXT        NOT NULL UNIQUE,
    -- Secret key: allows *reading* data. We store only its SHA-256 hash, so a
    -- leaked database dump does not leak usable keys.
    secret_key_hash BYTEA       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (organization_id, name)
);

CREATE TABLE issues (
    id          BIGSERIAL PRIMARY KEY,
    project_id  BIGINT      NOT NULL REFERENCES projects (id),
    fingerprint TEXT        NOT NULL,
    title       TEXT        NOT NULL,
    culprit     TEXT        NOT NULL DEFAULT '',
    status      TEXT        NOT NULL DEFAULT 'unresolved',
    event_count BIGINT      NOT NULL DEFAULT 0,
    first_seen  TIMESTAMPTZ NOT NULL,
    last_seen   TIMESTAMPTZ NOT NULL,
    -- One issue per fingerprint per project; the worker relies on this for
    -- its INSERT ... ON CONFLICT upsert.
    UNIQUE (project_id, fingerprint)
);

CREATE INDEX issues_project_last_seen ON issues (project_id, last_seen DESC);

CREATE TABLE events (
    project_id  BIGINT      NOT NULL REFERENCES projects (id),
    -- Generated by the SDK. The primary key makes a retried event a no-op.
    event_id    UUID        NOT NULL,
    issue_id    BIGINT      NOT NULL REFERENCES issues (id),
    timestamp   TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    platform    TEXT        NOT NULL,
    release     TEXT        NOT NULL DEFAULT '',
    environment TEXT        NOT NULL,
    payload     JSONB       NOT NULL,
    PRIMARY KEY (project_id, event_id)
);

CREATE INDEX events_issue_timestamp ON events (issue_id, timestamp DESC);

