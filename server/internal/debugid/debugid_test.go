// The React Native Metro plugin has its own copy of the snippet (it can't
// call Go). Both are checked against this file, so they can't drift apart.
func TestSnippetMatchesSharedTemplate(t *testing.T) {
	want, err := os.ReadFile("testdata/snippet.txt")
	if err != nil {
		t.Fatal(err)
	}
	if got := Snippet("{{ID}}"); got != string(want) {
		t.Errorf("Snippet differs from testdata/snippet.txt:\n got %s\nwant %s", got, want)
	}
}

func TestForContent(t *testing.T) {
	a, b := ForContent([]byte("bundle one")), ForContent([]byte("bundle two"))
	if a != ForContent([]byte("bundle one")) {
		t.Error("same bundle, different id")
	}
	if a == b {
		t.Error("different bundles, same id")
	}
	if !regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`).MatchString(a) {
		t.Errorf("%s isn't shaped like a version 4 UUID", a)
	}
}

const simpleMap = `{"version":3,"sources":["a.js"],"names":[],"mappings":"AAAA;AACA"}`

func TestInject(t *testing.T) {
	js, m, id, err := Inject([]byte("console.log(1);\nconsole.log(2);\n"), []byte(simpleMap))
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(string(js), "\n")
	if lines[0] != Snippet(id) || lines[1] != "console.log(1);" || !strings.Contains(string(js), "//# debugId="+id) {
		t.Errorf("bundle:\n%s", js)
	}
	var got map[string]any
	json.Unmarshal(m, &got)
	if got["mappings"] != ";AAAA;AACA" || got["debugId"] != id {
		t.Errorf("map = %v", got)
	}
	if FromBundle(js) != id || FromSourceMap(m) != id {
		t.Error("id not readable back from the outputs")
	}

	// Again: nothing changes, and the map isn't shifted a second time.
	js2, m2, id2, err := Inject(js, m)
	if err != nil || id2 != id || string(js2) != string(js) {
		t.Fatalf("second inject changed the bundle: %v", err)
	}
	json.Unmarshal(m2, &got)
	if got["mappings"] != ";AAAA;AACA" {
		t.Errorf("second inject shifted the map again: %v", got["mappings"])
	}
}

// Putting code before "use strict" would turn the bundle back to sloppy
// mode, a silent change in how it runs. The directive must stay first.
func TestInjectKeepsUseStrictFirst(t *testing.T) {
	for _, tc := range []struct {
		name, js string
		strict   bool
	}{
		{"plain", "var a=1;", false},
		{"use strict", `"use strict";var a=1;`, true},
		{"single quotes", `'use strict';var a=1;`, true},
		{"after a license comment", "/*! shop v1 | MIT */\n\"use strict\";var a=1;", true},
		{"after a line comment", "// built by esbuild\n'use strict'\nvar a=1;", true},
		{"after another directive", `"use client";"use strict";var a=1;`, true},
		{"inside a function only", `(function(){"use strict";})();`, false},
		{"a string that isn't first", `var s="use strict";`, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			js, _, _, err := Inject([]byte(tc.js), []byte(simpleMap))
			if err != nil {
				t.Fatal(err)
			}
			first := strings.SplitN(string(js), "\n", 2)[0]
			if got := strings.HasPrefix(first, `"use strict";`); got != tc.strict {
				t.Errorf("first line %q: starts with \"use strict\" = %v, want %v", first, got, tc.strict)
			}
		})
	}
}

func TestInjectIndexMap(t *testing.T) {
	m := `{"version":3,"sections":[{"offset":{"line":0,"column":0},"map":` + simpleMap + `},{"offset":{"line":5,"column":0},"map":` + simpleMap + `}]}`
	_, out, id, err := Inject([]byte("a\nb\n"), []byte(m))
	if err != nil {
		t.Fatal(err)
	}
	var got struct {
		DebugID  string
		Sections []struct{ Offset struct{ Line int } }
	}
	json.Unmarshal(out, &got)
	if got.DebugID != id || got.Sections[0].Offset.Line != 1 || got.Sections[1].Offset.Line != 6 {
		t.Errorf("index map: %s", out)
	}
}

func TestInjectRefuses(t *testing.T) {
	if _, _, _, err := Inject([]byte("#!/usr/bin/env node\nx()"), []byte(simpleMap)); err == nil {
		t.Error("a #! script was accepted")
	}
	if _, _, _, err := Inject([]byte("x()"), []byte("not json")); err == nil {
		t.Error("a broken map was accepted")
	}
	if _, _, _, err := Inject([]byte("x()"), []byte(`{"version":3}`)); err == nil {
		t.Error("a map without mappings was accepted")
	}
}

func TestFromSourceMap(t *testing.T) {
	const id = "4f1a2b3c-0000-4d5e-8f90-abcdef012345"
	snippetSource, _ := json.Marshal("// generated by @juju/react-native\n" + Snippet(id) + "\n")
	for _, tc := range []struct{ name, m, want string }{
		{"debugId field", `{"version":3,"mappings":"","debugId":"4F1A2B3C-0000-4D5E-8F90-ABCDEF012345"}`, id},
		{"debug_id field", `{"version":3,"mappings":"","debug_id":"` + id + `"}`, id},
		// React Native: the snippet's own source, kept in the composed map.
		{"snippet in sourcesContent", `{"version":3,"mappings":"","sources":["a.js","juju-debug-id.js"],"sourcesContent":["x()",` + string(snippetSource) + `]}`, id},
		{"null sourcesContent entries", `{"version":3,"mappings":"","sourcesContent":[null,` + string(snippetSource) + `]}`, id},
		{"inside a section", `{"version":3,"sections":[{"offset":{"line":0,"column":0},"map":{"version":3,"mappings":"","debugId":"` + id + `"}}]}`, id},
		{"none", simpleMap, ""},
		{"not an id", `{"version":3,"mappings":"","debugId":"build-42"}`, ""},
		{"code that only mentions the name", `{"version":3,"mappings":"","sourcesContent":["const ids = globalThis.__jujuDebugIds;"]}`, ""},
		{"not JSON", `nope`, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := FromSourceMap([]byte(tc.m)); got != tc.want {
				t.Errorf("got %q, want %q", got, tc.want)
			}
		})
	}
}

// A run can stop after writing one file but not the other. Running it
// again must end with the same files as one clean run: never a map shifted
// twice (every line off by one) or not at all.
func TestInjectAfterAnInterruptedRun(t *testing.T) {
	js := []byte("console.log(1);\nconsole.log(2);\n")
	cleanJS, cleanMap, id, err := Inject(js, []byte(simpleMap))
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct{ name, js, m string }{
		{"map written, bundle not", string(js), string(cleanMap)},
		{"bundle written, map not", string(cleanJS), simpleMap},
	} {
		t.Run(tc.name, func(t *testing.T) {
			gotJS, gotMap, gotID, err := Inject([]byte(tc.js), []byte(tc.m))
			if err != nil {
				t.Fatal(err)
			}
			var got, want map[string]any
			json.Unmarshal(gotMap, &got)
			json.Unmarshal(cleanMap, &want)
			if gotID != id || string(gotJS) != string(cleanJS) || got["mappings"] != want["mappings"] {
				t.Errorf("got id %s mappings %v, want %s %v", gotID, got["mappings"], id, want["mappings"])
			}
		})
	}
}

// Uploaded maps and bundles are whatever a build (or anyone with the
// secret key) sends: reading and stamping them must never panic, and
// whatever Inject accepts must come out stamped, and stay the same when
// stamped again.
func FuzzInject(f *testing.F) {
	f.Add([]byte("console.log(1)\n"), []byte(simpleMap))
	f.Add([]byte(`"use strict";x()`), []byte(`{"version":3,"sections":[{"offset":{"line":0,"column":0},"map":{}}]}`))
	f.Add([]byte("/* a */ 'use strict'"), []byte(`{"mappings":"","debugId":"4f1a2b3c-0000-4d5e-8f90-abcdef012345"}`))
	f.Add([]byte("x"), []byte(`{"mappings":"","sourcesContent":[null,"__jujuDebugIds=g.__jujuDebugIds||{})[s]=\"4f1a2b3c-0000-4d5e-8f90-abcdef012345\""]}`))
	f.Fuzz(func(t *testing.T, js, sm []byte) {
		FromSourceMap(sm)
		FromBundle(js)
		newJS, newMap, id, err := Inject(js, sm)
		if err != nil {
			return
		}
		if FromBundle(newJS) != id || FromSourceMap(newMap) != id {
			t.Fatalf("stamped outputs don't carry id %s", id)
		}
		againJS, againMap, againID, err := Inject(newJS, newMap)
		if err != nil || againID != id || string(againJS) != string(newJS) || string(againMap) != string(newMap) {
			t.Fatalf("second inject changed something: %v", err)
		}
	})
}
