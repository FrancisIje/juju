#!/bin/sh
# Builds docs/index.html, a complete web page for GitHub Pages, from
# docs/_src/roadmap.html, which holds only the page body because that is the
# format the Claude artifact viewer expects. One source, two outputs, so the
# copies can't drift apart.
#
# Usage: make docs
set -eu

src=docs/_src/roadmap.html
out=docs/index.html

# The source starts with <title>, <link> and <style>; those belong in <head>.
# Everything after the first </style> is the visible page and goes in <body>.
split=$(grep -n '</style>' "$src" | head -n 1 | cut -d: -f1)

{
  cat <<EOF
<!doctype html>
<!-- Generated by scripts/build-docs.sh from $src. Edit that file, then run: make docs -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
EOF
  head -n "$split" "$src"
  printf '</head>\n<body>\n'
  tail -n "+$((split + 1))" "$src"
  # The artifact viewer draws Mermaid diagrams by itself; a normal browser
  # needs the library. Pinned to an exact version so the page can't break
  # when Mermaid releases a new one.
  cat <<'EOF'
<script src="https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.min.js"></script>
<script>
  mermaid.initialize({
    startOnLoad: true,
    theme: matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "default",
  });
</script>
</body>
</html>
EOF
} > "$out"

echo "wrote $out"
